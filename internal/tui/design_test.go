// The Claude Design package (docs/design/control-center) is the brief and
// every golden frame in colour, on a dark and a light terminal. It is built
// from the same frames as TestDesignFrames, so a UI change that rewrites them
// (HIVE_UPDATE_FRAMES=1) rewrites the package too, and one that doesn't
// fails here until it does.
const designDir = "../../docs/design/control-center/"

// designShot is one frame in colour: its name, size and both themes' views.
type designShot struct {
	name        string
	w, h        int
	dark, light string
}

// colourShot renders m in true colour on a dark and a light terminal, as on
// Linux: unix gives Windows' paths forward slashes, and macOS's image key is
// set to the others' while it draws.
func colourShot(name string, w, h int, m *model, unix func(string) string) designShot {
	lipgloss.SetColorProfile(termenv.TrueColor)
	defer lipgloss.SetColorProfile(termenv.Ascii)
	defer lipgloss.SetHasDarkBackground(lipgloss.HasDarkBackground())
	defer func(k string) { imageKey = k }(imageKey)
	imageKey = "alt+v"
	s := designShot{name: name, w: w, h: h}
	lipgloss.SetHasDarkBackground(true)
	s.dark = unix(m.View())
	lipgloss.SetHasDarkBackground(false)
	s.light = unix(m.View())
	return s
}

// checkDesignPackage writes the package's frames page, or checks it is
// current, and checks the brief names every frame.
func checkDesignPackage(t *testing.T, shots []designShot) {
	t.Helper()
	page := framesPage(shots)
	if os.Getenv("HIVE_UPDATE_FRAMES") != "" {
		os.WriteFile(designDir+"frames.html", []byte(page), 0o644)
	} else if have, _ := os.ReadFile(designDir + "frames.html"); string(have) != page {
		t.Errorf("docs/design/control-center/frames.html is out of date with the frames: run HIVE_UPDATE_FRAMES=1 go test ./internal/tui -run TestDesignFrames and say in the brief what changed")
	}
	brief, err := os.ReadFile(designDir + "brief.md")
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range shots {
		if !strings.Contains(string(brief), "`"+s.name+"`") {
			t.Errorf("docs/design/control-center/brief.md doesn't describe the frame `%s`", s.name)
		}
	}
}

// framesPage is one self-contained HTML page: each frame as a terminal
// screen, dark beside light.
func framesPage(shots []designShot) string {
	var b strings.Builder
	b.WriteString(`<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>The Hive's control center: golden frames</title>
<!-- Generated by internal/tui/design_test.go from the golden frames; don't edit by hand. -->
<style>
body { font-family: system-ui, sans-serif; margin: 24px; background: #f6f8fa; color: #1f2328; }
h2 { font-size: 15px; margin: 32px 0 8px; }
.pair { display: flex; gap: 16px; flex-wrap: wrap; align-items: flex-start; }
pre { font: 13px/1.25 "JetBrains Mono", "SF Mono", Menlo, Consolas, monospace; padding: 8px; margin: 0; border-radius: 6px; }
.dark { background: #0d1117; color: #e6edf3; }
.light { background: #ffffff; color: #1f2328; border: 1px solid #d0d7de; }
.b { font-weight: bold; } .f { opacity: .55; } .i { font-style: italic; } .u { text-decoration: underline; }
</style></head><body>
<h1>The Hive's control center: golden frames</h1>
<p>Every frame in internal/tui/testdata, rendered by the real code in true colour, on a dark terminal and a light one. The brief beside this file says what each shows.</p>
`)
	for _, s := range shots {
		fmt.Fprintf(&b, "<h2 id=%q>%s · %d×%d</h2>\n<div class=\"pair\">\n", s.name, s.name, s.w, s.h)
		for _, v := range [][2]string{{"dark", s.dark}, {"light", s.light}} {
			fmt.Fprintf(&b, "<pre class=%q>%s</pre>\n", v[0], ansiHTML(v[1], v[0] == "dark"))
		}
		b.WriteString("</div>\n")
	}
	b.WriteString("</body></html>\n")
	return b.String()
}

var sgrRe = regexp.MustCompile(`\x1b\[([0-9;:]*)m`)

// basic16 is the 16 ANSI colours as a GitHub-like terminal shows them.
var basic16 = [2][8]string{
	{"#484f58", "#ff7b72", "#3fb950", "#d29922", "#58a6ff", "#bc8cff", "#39c5cf", "#b1bac4"}, // dark
	{"#24292f", "#cf222e", "#116329", "#4d2d00", "#0969da", "#8250df", "#1b7c83", "#6e7781"}, // light
}

// ansiHTML turns a view's SGR escapes into spans: bold, faint, italic,
// underline, reverse and colour. Anything else in the view is text.
func ansiHTML(view string, dark bool) string {
	fg0, bg0 := "#e6edf3", "#0d1117"
	pal := basic16[0]
	if !dark {
		fg0, bg0, pal = "#1f2328", "#ffffff", basic16[1]
	}
	var bold, faint, ital, under, rev bool
	var fg, bg string
	var b strings.Builder
	open := false
	style := func() {
		if open {
			b.WriteString("</span>")
			open = false
		}
		f, g := fg, bg
		if rev {
			f, g = bg, fg
			if f == "" {
				f = bg0
			}
			if g == "" {
				g = fg0
			}
		}
		var cls []string
		for _, c := range []struct {
			on   bool
			name string
		}{{bold, "b"}, {faint, "f"}, {ital, "i"}, {under, "u"}} {
			if c.on {
				cls = append(cls, c.name)
			}
		}
		var css []string
		if f != "" {
			css = append(css, "color:"+f)
		}
		if g != "" {
			css = append(css, "background:"+g)
		}
		if len(cls) == 0 && len(css) == 0 {
			return
		}
		b.WriteString("<span")
		if len(cls) > 0 {
			fmt.Fprintf(&b, ` class="%s"`, strings.Join(cls, " "))
		}
		if len(css) > 0 {
			fmt.Fprintf(&b, ` style="%s"`, strings.Join(css, ";"))
		}
		b.WriteString(">")
		open = true
	}
	last := 0
	for _, loc := range sgrRe.FindAllStringSubmatchIndex(view, -1) {
		b.WriteString(html.EscapeString(view[last:loc[0]]))
		last = loc[1]
		ps := strings.FieldsFunc(view[loc[2]:loc[3]], func(r rune) bool { return r == ';' || r == ':' })
		if len(ps) == 0 {
			ps = []string{"0"}
		}
		for i := 0; i < len(ps); i++ {
			n, _ := strconv.Atoi(ps[i])
			switch {
			case n == 0:
				bold, faint, ital, under, rev, fg, bg = false, false, false, false, false, "", ""
			case n == 1:
				bold = true
			case n == 2:
				faint = true
			case n == 3:
				ital = true
			case n == 4:
				under = true
			case n == 7:
				rev = true
			case n == 22:
				bold, faint = false, false
			case n == 23:
				ital = false
			case n == 24:
				under = false
			case n == 27:
				rev = false
			case n >= 30 && n <= 37:
				fg = pal[n-30]
			case n >= 90 && n <= 97:
				fg = pal[n-90]
			case n == 39:
				fg = ""
			case n >= 40 && n <= 47:
				bg = pal[n-40]
			case n >= 100 && n <= 107:
				bg = pal[n-100]
			case n == 49:
				bg = ""
			case (n == 38 || n == 48) && i+4 < len(ps) && ps[i+1] == "2":
				r, _ := strconv.Atoi(ps[i+2])
				g, _ := strconv.Atoi(ps[i+3])
				bl, _ := strconv.Atoi(ps[i+4])
				c := fmt.Sprintf("#%02X%02X%02X", r, g, bl)
				if n == 38 {
					fg = c
				} else {
					bg = c
				}
				i += 4
			case (n == 38 || n == 48) && i+2 < len(ps) && ps[i+1] == "5":
				i += 2 // 256 colours: the palette doesn't use them
			}
		}
		style()
	}
	b.WriteString(html.EscapeString(view[last:]))
	if open {
		b.WriteString("</span>")
	}
	return b.String()
}
