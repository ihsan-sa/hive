#!/usr/bin/env python3
"""Write core/hive-help.md: one paragraph per hive subcommand, from core/hive's own parser and docstrings, so `kb find` finds them.

The hive script is read with ast, never run. `gen_h2_help.py --check` writes nothing and exits 1 if the file is stale.
"""
import ast, sys
from pathlib import Path

CORE = Path(__file__).resolve().parent
SRC, OUT = CORE / "hive", CORE / "hive-help.md"
SHORT = 80  # a help line shorter than this also gets the command's docstring
HEAD = "# hive commands\n\nGenerated by core/gen_h2_help.py from core/hive's parser and docstrings. Don't edit: run the generator.\n"

def text(call, kw):
    """A keyword argument of a call, if it is a plain string."""
    for k in call.keywords:
        if k.arg == kw and isinstance(k.value, ast.Constant) and isinstance(k.value.value, str): return k.value.value

def clean(s):
    return " ".join(s.replace("%%", "%").split())

def calls(stmt, attr):
    return [n for n in ast.walk(stmt) if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr == attr]

def commands(src):
    """[{name, help, flags, doc}] in the parser's order. Only statements at the top of the file count: that is where hive builds its parser."""
    tree = ast.parse(src)
    docs = {n.name: ast.get_docstring(n) for n in tree.body if isinstance(n, ast.FunctionDef)}
    out, cur = [], None
    for stmt in tree.body:
        if isinstance(stmt, (ast.FunctionDef, ast.If)): continue  # a def's own calls, and the `if sys.argv` hand-overs
        for c in calls(stmt, "add_parser"):
            if isinstance(c.func.value, ast.Name) and c.func.value.id == "sp" and c.args and isinstance(c.args[0], ast.Constant):
                cur = {"name": c.args[0].value, "help": text(c, "help") or "", "flags": [], "doc": docs.get("cmd_" + c.args[0].value.replace("-", "_"))}
                out.append(cur)
        if cur is None: continue
        for c in calls(stmt, "add_argument"):
            names = [x.value for x in c.args if isinstance(x, ast.Constant) and isinstance(x.value, str)]
            flag = next((n for n in names if n.startswith("--")), None) or (names[0] if names else None)
            if flag and flag.startswith("-") and text(c, "help"): cur["flags"].append(f"`{flag}`: {clean(text(c, 'help'))}")
        for c in calls(stmt, "set_defaults"):
            for k in c.keywords:
                if k.arg == "f" and isinstance(k.value, ast.Name) and docs.get(k.value.id): cur["doc"] = docs[k.value.id]
    return out

def render(src):
    parts = [HEAD]
    for c in commands(src):
        words = clean(c["help"])
        doc = clean(c["doc"] or "")
        if len(words) < SHORT and doc not in words: words = f"{words}. {doc}" if words and doc else words or doc  # a long help already says what the docstring says
        para = f"## hive {c['name']}\n\n{words}"
        if c["flags"]: para += " Flags: " + "; ".join(c["flags"]) + "."
        parts.append(para + "\n")
    return "\n".join(parts)

def main():
    want = render(SRC.read_text())
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != want:
            sys.exit("hive-help.md is stale: run python3 core/gen_h2_help.py")
        return
    OUT.write_text(want)

if __name__ == "__main__": main()
